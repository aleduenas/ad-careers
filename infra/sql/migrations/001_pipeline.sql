CREATE TABLE jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company text NOT NULL,
  role text NOT NULL,
  url text,
  url_key text UNIQUE,
  status text NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Evaluated','Applied','Interview','Offer','Rejected','Discarded','SKIP')),
  notes text NOT NULL DEFAULT '',
  score numeric CHECK (score BETWEEN 0 AND 5),
  report_path text,
  jd_path text,
  source_date date,
  created_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  applied_at timestamptz,
  evaluated_at timestamptz,
  revision bigint NOT NULL DEFAULT 0,
  evaluation_error text
);
CREATE INDEX jobs_status_id ON jobs(status,id);
CREATE TABLE evaluations (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL REFERENCES jobs(id),
  operation_key text NOT NULL UNIQUE,
  score numeric CHECK (score BETWEEN 0 AND 5),
  report_path text NOT NULL,
  result_status text NOT NULL CHECK (result_status IN ('Evaluated','SKIP','Discarded')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE job_status_events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL REFERENCES jobs(id),
  old_status text,
  new_status text NOT NULL,
  reason text NOT NULL DEFAULT '',
  actor text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX job_status_events_job ON job_status_events(job_id,id);
CREATE TABLE workflow_claims (
  resource text PRIMARY KEY,
  owner_token text NOT NULL,
  expires_at timestamptz NOT NULL
);
CREATE TABLE scan_history (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  url text NOT NULL,
  first_seen date,
  portal text NOT NULL DEFAULT '',
  title text NOT NULL DEFAULT '',
  company text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT '',
  location text NOT NULL DEFAULT ''
);
CREATE INDEX scan_history_url ON scan_history(url);
CREATE TABLE legacy_imports (
  fingerprint text PRIMARY KEY,
  imported_at timestamptz NOT NULL DEFAULT now(),
  job_count integer NOT NULL
);
CREATE FUNCTION create_job(p_company text,p_role text,p_url text,p_key text,p_jd text)
RETURNS jobs LANGUAGE plpgsql AS $$
DECLARE result jobs;
BEGIN
  INSERT INTO jobs(company,role,url,url_key,jd_path,created_at)
  VALUES(p_company,p_role,p_url,p_key,p_jd,now())
  ON CONFLICT(url_key) DO NOTHING RETURNING * INTO result;
  IF result.id IS NULL THEN SELECT * INTO result FROM jobs WHERE url_key=p_key; END IF;
  RETURN result;
END $$;
CREATE FUNCTION change_job_status(p_id bigint,p_revision bigint,p_status text,p_reason text,p_actor text)
RETURNS jobs LANGUAGE plpgsql AS $$
DECLARE result jobs; previous text;
BEGIN
  SELECT * INTO result FROM jobs WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Job % does not exist',p_id; END IF;
  IF result.revision<>p_revision THEN RAISE EXCEPTION 'Revision conflict for job %; refresh and retry',p_id USING ERRCODE='40001'; END IF;
  previous:=result.status;
  UPDATE jobs SET status=p_status,revision=revision+1,updated_at=now(),
    applied_at=CASE WHEN p_status='Applied' THEN coalesce(applied_at,now()) ELSE applied_at END,
    notes=CASE WHEN p_reason='' THEN notes ELSE concat_ws(E'\n',nullif(notes,''),p_reason) END
    WHERE id=p_id RETURNING * INTO result;
  INSERT INTO job_status_events(job_id,old_status,new_status,reason,actor) VALUES(p_id,previous,p_status,p_reason,p_actor);
  RETURN result;
END $$;
CREATE FUNCTION claim_work(p_resource text,p_owner text,p_seconds integer)
RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
  IF p_seconds<1 OR p_seconds>3600 THEN RAISE EXCEPTION 'Invalid lease duration'; END IF;
  INSERT INTO workflow_claims VALUES(p_resource,p_owner,now()+make_interval(secs=>p_seconds))
  ON CONFLICT(resource) DO UPDATE SET owner_token=excluded.owner_token,expires_at=excluded.expires_at
  WHERE workflow_claims.expires_at<now() OR workflow_claims.owner_token=p_owner;
  RETURN FOUND;
END $$;
CREATE FUNCTION complete_evaluation(p_id bigint,p_owner text,p_key text,p_score numeric,p_report text,p_status text,p_note text)
RETURNS jobs LANGUAGE plpgsql AS $$
DECLARE result jobs; previous text; existing evaluations;
BEGIN
  SELECT * INTO result FROM jobs WHERE id=p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown job %',p_id; END IF;
  SELECT * INTO existing FROM evaluations WHERE operation_key=p_key;
  IF FOUND THEN
    IF existing.job_id<>p_id OR existing.report_path<>p_report OR existing.score IS DISTINCT FROM p_score OR existing.result_status<>p_status THEN
      RAISE EXCEPTION 'Conflicting idempotency key';
    END IF;
    RETURN result;
  END IF;
  PERFORM 1 FROM workflow_claims WHERE resource='evaluation:'||p_id AND owner_token=p_owner AND expires_at>now() FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Evaluation lease lost for %',p_id; END IF;
  INSERT INTO evaluations(job_id,operation_key,score,report_path,result_status) VALUES(p_id,p_key,p_score,p_report,p_status);
  previous:=result.status;
  UPDATE jobs SET score=p_score,report_path=p_report,evaluated_at=now(),updated_at=now(),revision=revision+1,
    status=CASE WHEN status='Pending' THEN p_status ELSE status END,
    notes=concat_ws(E'\n',nullif(notes,''),nullif(p_note,'')),evaluation_error=NULL
    WHERE id=p_id RETURNING * INTO result;
  IF previous<>result.status THEN
    INSERT INTO job_status_events(job_id,old_status,new_status,reason,actor) VALUES(p_id,previous,result.status,p_note,'evaluation');
  END IF;
  RETURN result;
END $$;
